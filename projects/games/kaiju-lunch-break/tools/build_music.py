#!/usr/bin/env python3
"""Fetch Kaiju Lunch Break's music and press it into CD-DA tracks for the disc.

assets/music/tracks.txt lists the songs (sha256, file name, title) in disc
order. Each mp3 is downloaded from KL_MUSIC_URL (default
https://dcvmu.com/kaiju-lunch-break/music/) into assets/music/cache/ unless
a copy with the right sha256 is already there, or KL_MUSIC_SOURCE names a
folder holding the files (no download then). The engine's
tools/cddamusic.py converts each to cdda/NN-<name>.wav, and the track table
is written to assets/generated/music_tracks.h.

Standard library only, so CI runs it with plain python3; locally `make
music` (or any target that needs the disc) runs it.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "common" / "engine" / "tools"))
import cddamusic  # noqa: E402

DEFAULT_URL = "https://dcvmu.com/kaiju-lunch-break/music/"


class Track:
    def __init__(self, sha256, name, title):
        self.sha256, self.name, self.title = sha256, name, title
        self.stem = name.rsplit(".", 1)[0]


def read_manifest(path):
    tracks = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 3 or len(parts[0]) != 64:
            raise SystemExit(f"{path}: bad line: {line}")
        tracks.append(Track(parts[0], parts[1], " ".join(parts[2:])))
    if not tracks:
        raise SystemExit(f"{path}: no tracks")
    return tracks


def write_header(path, tracks, seconds):
    h = ["/* Generated by tools/build_music.py from assets/music/tracks.txt. Do not edit by hand. */",
         "#ifndef KL_MUSIC_TRACKS_H", "#define KL_MUSIC_TRACKS_H", "",
         "/* The disc's CD-DA tracks in order. */",
         f"#define KL_MUSIC_TRACKS {len(tracks)}",
         "static const char *const kl_music_title[KL_MUSIC_TRACKS] __attribute__((unused)) = {"]
    h += [f'    "{t.title}",' for t in tracks]
    h += ["};", "/* Length in seconds. */",
          "static const float kl_music_secs[KL_MUSIC_TRACKS] __attribute__((unused)) = {"
          + ", ".join(f"{s:.1f}f" for s in seconds) + "};",
          "", "#endif /* KL_MUSIC_TRACKS_H */", ""]
    text = "\n".join(h)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
        print(f"music: wrote {path}")


def main():
    project = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--project-dir", type=Path, default=project)
    ap.add_argument("--url", default=os.environ.get("KL_MUSIC_URL", DEFAULT_URL),
                    help="where the mp3s are downloaded from (KL_MUSIC_URL)")
    ap.add_argument("--source", type=Path, default=os.environ.get("KL_MUSIC_SOURCE") or None,
                    help="a folder already holding the mp3s, copied instead of downloaded (KL_MUSIC_SOURCE)")
    args = ap.parse_args()
    project = args.project_dir
    tracks = read_manifest(project / "assets/music/tracks.txt")
    seconds = cddamusic.press(project, tracks, args.url, args.source, __file__, "kaiju-lunch-break-build")
    write_header(project / "assets/generated/music_tracks.h", tracks, seconds)


if __name__ == "__main__":
    main()
