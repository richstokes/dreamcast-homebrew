#include <stdint.h>

/*
 * Compact, header-only meshes for Gravity Wave.
 *
 * Coordinate convention: +Z forward, +Y up, and X across the wingspan.
 * UV coordinates address the complete vehicle atlas and stay in [0, 1].
 * Material ids are shared with the renderer:
 *   0 allied hull, 1 hostile hull, 2 canopy/energy, 3 ancient machinery.
 */

typedef struct {
    float x, y, z;
    float u, v;
} gravity_wave_mesh_vertex_t;

typedef struct {
    uint8_t a, b, c, material;
} gravity_wave_mesh_face_t;

typedef struct {
    const gravity_wave_mesh_vertex_t *vertices;
    const gravity_wave_mesh_face_t *faces;
    uint16_t vertex_count;
    uint16_t face_count;
    float radius;
} gravity_wave_mesh_t;

#define GRAVITY_WAVE_MESH_COUNT_OF(a) ((uint16_t)(sizeof(a) / sizeof((a)[0])))

